"""Expand new consequential deliverables into two ordered, version-bound reviews."""

from copy import deepcopy
import hashlib


STAGES = {
    "requirements": "Check every original requirement and acceptance criterion, including missing or extra behavior. "
                    "List concrete gaps. Do not substitute the implementer's summary for inspecting the deliverable.",
    "quality": "Check correctness, edge cases, maintainability, security and relevant test coverage. "
               "Consider unresolved disagreements and missing evidence. Do not infer success from model confidence.",
}


def _review_id(target, stage):
    digest = hashlib.sha256(target.encode("utf-8")).hexdigest()[:16]
    return f"review-{digest}-{stage}"


def expand_reviews(tasks):
    """Only new plans expand; existing checkpoint graphs retain their saved semantics."""
    expanded = deepcopy(tasks)
    gates = {}
    generated = []
    ids = {task.get("id") for task in tasks}
    for task in expanded:
        policy = task.get("review_policy", "auto")
        if policy not in {"auto", "two_stage"}:
            raise ValueError("review_policy must be auto or two_stage.")
        if "review_stage" in task:
            raise ValueError("Review stages are generated by the coordinator, not supplied in a plan.")
        if "review_of" in task:
            if policy != "auto":
                raise ValueError("Set review_policy on the deliverable, not on a reviewer.")
            continue
        required = policy == "two_stage" or (task.get("write_paths") and task.get("workload") in {"standard", "complex"})
        if not required:
            continue
        target = task["id"]
        previous = None
        for stage, instruction in STAGES.items():
            key = _review_id(target, stage)
            if key in ids:
                raise ValueError("A task id conflicts with a generated review id; rename that task.")
            ids.add(key)
            generated.append({
                "id": key, "goal": f"{stage.capitalize()} review: {task['goal']}",
                "review_of": target, "review_stage": stage,
                "depends_on": [target] + ([previous] if previous else []),
                "workload": "complex", "parallel_safe": True, "tool_access": "files_only", "write_paths": [],
                "acceptance": instruction + " Return pass, needs_fix or inconclusive with an actual check and observation.",
            })
            previous = key
        gates[target] = previous
    for task in expanded:
        if "review_of" not in task:
            dependencies = list(task.get("depends_on", []))
            task["depends_on"] = dependencies + [gates[dep] for dep in dependencies if dep in gates]
    return expanded + generated


def reset_reviews(record, target_id):
    """A repaired version needs both checks again; attempts never reset to zero."""
    for row in record["tasks"].values():
        task = row["task"]
        if task.get("review_of") != target_id or not task.get("review_stage"):
            continue
        row.pop("error", None)
        row.update(state="pending", artifacts={})
        if row["attempt"] >= 3:
            row.update(state="failed", error="Review reached its three-attempt limit; unresolved work remains unverified.")


def refresh_reviews(record, target_id):
    target = record["tasks"][target_id]
    for row in record["tasks"].values():
        if row["task"].get("review_of") == target_id and row["task"].get("review_stage") and "reviewed_attempt" in row:
            if (row["reviewed_attempt"] != target["attempt"]
                    or row.get("reviewed_artifacts") != target.get("artifacts", {})):
                reset_reviews(record, target_id)
                return
